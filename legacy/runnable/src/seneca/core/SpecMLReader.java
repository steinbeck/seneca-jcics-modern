	public static org.w3c.dom.Document openDocument(File file)
	{
		org.w3c.dom.Document document = null;
		InputSource input = null;

		DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
		try
		{
			DocumentBuilder builder = factory.newDocumentBuilder();
			document = builder.parse(file);

		} catch (SAXParseException spe)
		{
			// Error generated by the parser
			if (debug) System.out.println ("\n** Parsing error" 
				+ ", line " + spe.getLineNumber ()
				+ ", uri " + spe.getSystemId ());
			if (debug) System.out.println("   " + spe.getMessage() );

			// Use the contained exception, if any
			Exception  x = spe;
			if (spe.getException() != null)
				x = spe.getException();
			x.printStackTrace();

		} catch (SAXException sxe)
		{
			// Error generated by this application
			// (or a parser-initialization error)
			Exception  x = sxe;
			if (sxe.getException() != null)
				x = sxe.getException();
			x.printStackTrace();

		} catch (ParserConfigurationException pce)
		{
			// Parser with specified options can't be built
			pce.printStackTrace();

		} catch (IOException ioe)
		{
			// I/O error
			ioe.printStackTrace();
		}
		return document;
	
	}

	public static org.w3c.dom.Node getDocStart(org.w3c.dom.Node node)
	{
		return getDocStart(node, "senecadataset");
	}

	public static org.w3c.dom.Node getDocStart(org.w3c.dom.Node node, String startTag)
	{
		org.w3c.dom.Node newNode = null; 

		for (int f = 0; f < node.getChildNodes().getLength(); f++)
		{
			newNode = node.getChildNodes().item(f);
			if (debug) System.out.println(node.getNodeName().toLowerCase());
			if (node.getNodeName().trim().toLowerCase().equals(startTag.trim().toLowerCase()))
			{
				docStart = true;
				startNode = node;
				return startNode;			
			}
		}

		for (int f = 0; f < node.getChildNodes().getLength(); f++)
		{
			newNode = node.getChildNodes().item(f);
			getDocStart(newNode, startTag);
			if (docStart) return startNode;
		}
		
		if (debug) System.out.println("Nothing found");
		return null;
	}



	private void readSDDomTree()
	{
		org.w3c.dom.Node node = getDocStart(document);
		if (!initSD(node)) return;
		handleSDParts(node);
	}
	
	private boolean initSD(org.w3c.dom.Node node)
	{
		sd = new SenecaDataset(node.getAttributes().getNamedItem("title").getNodeValue());
		return true;
	}
	
	private void handleSDParts(org.w3c.dom.Node node)
	{
		org.w3c.dom.Node newNode = null;
		String nodeName = null; 
		for (int f = 0; f < node.getChildNodes().getLength(); f++)
		{
			newNode = node.getChildNodes().item(f);
			if (typeName[newNode.getNodeType()].equals("Element"))
			{
				nodeName = newNode.getNodeName();
				if (nodeName.toLowerCase().equals("formula"))				
				{
					readFormula(newNode);
				}
				if (nodeName.toLowerCase().equals("cml:molecule"))				
				{
					readMolecule(newNode);
				}				
				if (nodeName.toLowerCase().equals("spectrum"))				
				{
					readSpectrum(newNode);
				}				
				if (nodeName.toLowerCase().equals("judge"))				
				{
					//readJudge(newNode);
				}				
				if (nodeName.toLowerCase().equals("annealingschedule"))				
				{
					readAnnealingSchedule(newNode);
				}				
				if (nodeName.toLowerCase().equals("serverinfo"))				
				{
					sd.serverList.addElement(readServerInfo(newNode));
				}				

			}
		}
	}
	

	private void readJudge(org.w3c.dom.Node node)
	{
		if (debug) System.out.println("readJudge");
		
		org.w3c.dom.Node newNode = null;
		String title = node.getAttributes().getNamedItem("title").getNodeValue();		
		String className = title + "Configurator";
		Class judgeConf = null;
		Method method = null;
		Class[] parameterTypes = new Class[1];
		Object[] parameters = new Object[1];
		try
		{
			judgeConf = Class.forName("seneca.client." + className);
		}
		catch(Exception exc)
		{
			System.err.println("No Configurator " + className + " found for judge " + className + "\n");
			exc.printStackTrace();
		}

		try
		{
			parameterTypes[0] = org.w3c.dom.Node.class;
			method = judgeConf.getMethod("getJudgeFromXML", parameterTypes);
			parameters[0] = node;
		}
		catch(Exception exc)
		{
			System.err.println("No getJudgeFromXML method found for judgeConfigurator " + className + "\n");
			exc.printStackTrace();
		}

	}


	private void readMolecule(org.w3c.dom.Node node)
	{
		if (debug) System.out.println("readMolecule");
	
		org.w3c.dom.Node newNode = null;
		Vector atoms = new Vector();
	
		for (int f = 0; f < node.getChildNodes().getLength(); f++)
		{
			newNode = node.getChildNodes().item(f);
			if (typeName[newNode.getNodeType()].equals("Element"))
			{
				if (newNode.getNodeName().toLowerCase().equals("atom"))
				{
					atoms.addElement(readAtom(newNode));	
				}
			}
		}
		compchem.Atom[] atomsArray = new compchem.Atom[atoms.size()];
		for (int f = 0; f < atoms.size(); f++) atomsArray[f] = (compchem.Atom)atoms.elementAt(f);		
		sd.setSetOfNodes(atomsArray);
	}


	private Atom readAtom(org.w3c.dom.Node node)
	{
		if (debug) System.out.println("readAtom");
		org.w3c.dom.Node newNode = null;
		compchem.Atom atom = new Atom();
		atom.HCount = -1;
		atom.name = node.getAttributes().getNamedItem("id").getNodeValue();		
		for (int f = 0; f < node.getChildNodes().getLength(); f++)
		{
			newNode = node.getChildNodes().item(f);
			if (typeName[newNode.getNodeType()].equals("Element"))
			{
				if (newNode.getNodeName().toLowerCase().equals("string"))
				{
					if (newNode.getAttributes().getNamedItem("builtin").getNodeValue().toLowerCase().equals("elementtype"))						
					{
						atom.symbol = newNode.getChildNodes().item(0).getNodeValue();						
						if (debug) System.out.println(atom.symbol);
					}
				}
				if (newNode.getNodeName().toLowerCase().equals("integer"))
				{
					if (newNode.getAttributes().getNamedItem("builtin").getNodeValue().toLowerCase().equals("hydrogencount"))						
					{
						atom.HCount = Integer.parseInt(newNode.getChildNodes().item(0).getNodeValue());						
						if (debug) System.out.println(atom.HCount);
					}
				}
				if (newNode.getNodeName().toLowerCase().equals("float"))
				{
					if (newNode.getAttributes().getNamedItem("title").getNodeValue().toLowerCase().equals("assignedcarbonshift"))						
					{
						atom.setPhysicalProperty(compchem.Atom.PHYS_PROP_13C_SHIFT, new Float(newNode.getChildNodes().item(0).getNodeValue()));						
						if (debug) System.out.println(atom.getPhysicalProperty(compchem.Atom.PHYS_PROP_13C_SHIFT));
					}
				}

			}
		}
		return atom;
	}


	private void readSpectrum (org.w3c.dom.Node node)
	{
		if (debug) System.out.println("readSpectrum");
		org.w3c.dom.Node newNode = null;
		NMRSpectrum nmrspect = null;		
		nmrspect = readSpectrumInfo(node);
		nmrspect.name = node.getAttributes().getNamedItem("id").getNodeValue();		
		for (int f = 0; f < node.getChildNodes().getLength(); f++)
		{
			newNode = node.getChildNodes().item(f);
			if (typeName[newNode.getNodeType()].equals("Element"))
			{
				if (newNode.getNodeName().toLowerCase().equals("signal"))
				{
					nmrspect.addSignal(readNMRSignal(newNode, nmrspect.nucleus));
				}
			}
		}
		if (debug) System.out.println("We found an nmr spectrum of type " + nmrspect.specType);
		if (nmrspect.specType.equals(SenecaDataset.carbon1d_name)) sd.carbon1D = nmrspect;
		if (nmrspect.specType.equals(SenecaDataset.dept90_name)) sd.dept90 = nmrspect;
		if (nmrspect.specType.equals(SenecaDataset.dept135_name)) sd.dept135 = nmrspect;				
		if (nmrspect.specType.equals(SenecaDataset.hhcosy_name)) sd.hhcosy = nmrspect;
		if (nmrspect.specType.equals(SenecaDataset.hetcor_name)) sd.hetcor = nmrspect;
		if (nmrspect.specType.equals(SenecaDataset.hetcorlr_name)) sd.hetcorlr = nmrspect;
		if (nmrspect.specType.equals(SenecaDataset.noesy_name)) sd.noesy = nmrspect;
	}

	private NMRSpectrum readSpectrumInfo(org.w3c.dom.Node node)
	{
		if (debug) System.out.println("readSpectrumInfo");
		org.w3c.dom.Node newNode = null;
		int dim = 0;
		String type = null, solvent = null, standard = null; 
		float frequency = 0; 
		String[] nuclei = new String[4];
		int axisinfoCounter = 0;
		NMRSpectrum nmrspect = null;
		for (int f = 0; f < node.getChildNodes().getLength(); f++)
		{
			newNode = node.getChildNodes().item(f);
			if (typeName[newNode.getNodeType()].equals("Element"))
			{
				if (newNode.getNodeName().toLowerCase().equals("spectruminfo"))
				{
					node = newNode; 
					for (int g = 0; g < node.getChildNodes().getLength(); g++)
					{
						newNode = node.getChildNodes().item(g);
						if (typeName[newNode.getNodeType()].equals("Element"))
						{
							if (newNode.getNodeName().toLowerCase().equals("dimension"))
							{
								if (newNode.getChildNodes().item(0) != null) dim = Integer.parseInt(newNode.getChildNodes().item(0).getNodeValue());	
							}
							if (newNode.getNodeName().toLowerCase().equals("type"))
							{
								if (newNode.getChildNodes().item(0) != null) type = newNode.getChildNodes().item(0).getNodeValue();	
							}
							if (newNode.getNodeName().toLowerCase().equals("frequency"))
							{
								if (newNode.getChildNodes().item(0) != null) frequency = Float.parseFloat(newNode.getChildNodes().item(0).getNodeValue());	
							}
							if (newNode.getNodeName().toLowerCase().equals("solvent"))
							{
								if (newNode.getChildNodes().item(0) != null) solvent = newNode.getChildNodes().item(0).getNodeValue(); 
							}
							if (newNode.getNodeName().toLowerCase().equals("standard"))
							{
								if (newNode.getChildNodes().item(0) != null) standard = newNode.getChildNodes().item(0).getNodeValue();	
							}
							if (newNode.getNodeName().toLowerCase().equals("axisinfo"))
							{
								readAxisInfo(newNode, nuclei);
								axisinfoCounter ++;
							}
				
						}
					}
				}
			}
		}
		String[] finalNuclei = new String[axisinfoCounter];
		System.arraycopy(nuclei, 0, finalNuclei, 0, finalNuclei.length);
		nmrspect = new NMRSpectrum(finalNuclei, null);
		nmrspect.setSolvent(solvent);
		nmrspect.specType = type;
		nmrspect.setSpectrometerFrequency(frequency);
		return nmrspect;
	}

	private void readAxisInfo(org.w3c.dom.Node node, String[] nuclei)
	{
		if (debug) System.out.println("readAxisInfo");
		String nucleus = null, property = null, unit = null; 
		org.w3c.dom.Node newNode = null;
		int dim = 0;
		int nucleiIndex = -1;
		String type = null, solvent = null, standard = null; 
		float frequency = 0; 
		String role = node.getAttributes().getNamedItem("role").getNodeValue();
		if (role.toLowerCase().equals("f1")) nucleiIndex = 0;
		if (role.toLowerCase().equals("f2")) nucleiIndex = 1;
		if (role.toLowerCase().equals("f3")) nucleiIndex = 2;
		if (role.toLowerCase().equals("f4")) nucleiIndex = 3;
		if (role.toLowerCase().equals("f5")) nucleiIndex = 4;
										
		for (int f = 0; f < node.getChildNodes().getLength(); f++)
		{
			newNode = node.getChildNodes().item(f);
			if (typeName[newNode.getNodeType()].equals("Element"))
			{
				if (newNode.getNodeName().toLowerCase().equals("nucleus"))
				{
					nucleus = newNode.getChildNodes().item(0).getNodeValue();	
				}
				if (newNode.getNodeName().toLowerCase().equals("property"))
				{
					property = newNode.getChildNodes().item(0).getNodeValue();	
				}
				if (newNode.getNodeName().toLowerCase().equals("unit"))
				{
					unit = newNode.getChildNodes().item(0).getNodeValue();	
				}
			}
		}
		nuclei[nucleiIndex] = nucleus;
	}


	private NMRSignal readNMRSignal(org.w3c.dom.Node node, String[] nucleus)
	{
		if (debug) System.out.println("readNMRSignal");
		org.w3c.dom.Node newNode = null;
		int dim = 0;
		int nucleiIndex = -1;
		NMRSignal nmrSig = new NMRSignal(nucleus);		
		for (int f = 0; f < node.getChildNodes().getLength(); f++)
		{
			newNode = node.getChildNodes().item(f);
			if (typeName[newNode.getNodeType()].equals("Element"))
			{
				if (newNode.getNodeName().toLowerCase().equals("location"))
				{
					nucleiIndex = -1;
					String role = newNode.getAttributes().getNamedItem("role").getNodeValue();
					if (role.toLowerCase().equals("f1")) nucleiIndex = 0;
					if (role.toLowerCase().equals("f2")) nucleiIndex = 1;
					if (role.toLowerCase().equals("f3")) nucleiIndex = 2;
					if (role.toLowerCase().equals("f4")) nucleiIndex = 3;
					if (role.toLowerCase().equals("f5")) nucleiIndex = 4;
					if (newNode.getChildNodes().item(0) != null)
					{
						nmrSig.setShift(Float.parseFloat(newNode.getChildNodes().item(0).getNodeValue()), nucleiIndex); 
					}
				}
				if (newNode.getNodeName().toLowerCase().equals("intensity"))
				{
					if (newNode.getChildNodes().item(0) != null)
					{
						nmrSig.intensity = Float.parseFloat(newNode.getChildNodes().item(0).getNodeValue());
					}
				}
				if (newNode.getNodeName().toLowerCase().equals("normalizefactor"))
				{
					if (newNode.getChildNodes().item(0) != null)
					{
						nmrSig.normalizeFactor = Float.parseFloat(newNode.getChildNodes().item(0).getNodeValue());
					}
				}
				if (newNode.getNodeName().toLowerCase().equals("phase"))
				{
					if (newNode.getChildNodes().item(0) != null)
					{
						nmrSig.phase = Integer.parseInt(newNode.getChildNodes().item(0).getNodeValue());
					}
				}
			}
		}
		return nmrSig;
	}


