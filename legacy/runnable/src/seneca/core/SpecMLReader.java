	private void readAnnealingSchedule (org.w3c.dom.Node node)
	{
		if (debug) System.out.println("readAnnealingSchedule");
		org.w3c.dom.Node newNode = null;
		AnnealingSchedule annSched = new AnnealingSchedule();
		for (int f = 0; f < node.getChildNodes().getLength(); f++)
		{
			newNode = node.getChildNodes().item(f);
			if (typeName[newNode.getNodeType()].equals("Element"))
			{
				if (newNode.getNodeName().toLowerCase().equals("initialAcceptanceProbability".toLowerCase()))
				{
					annSched.initialAcceptanceProbability = Double.parseDouble(newNode.getChildNodes().item(0).getNodeValue());
				}
				if (newNode.getNodeName().toLowerCase().equals("maxUphillSteps".toLowerCase()))
				{
					annSched.maxUphillSteps = Long.parseLong(newNode.getChildNodes().item(0).getNodeValue());
				}
				if (newNode.getNodeName().toLowerCase().equals("plateauSteps".toLowerCase()))
				{
					annSched.plateauSteps = Long.parseLong(newNode.getChildNodes().item(0).getNodeValue());
				}
				if (newNode.getNodeName().toLowerCase().equals("asymptoticCoolingFactor".toLowerCase()))
				{
					annSched.asymptoticCoolingFactor = Double.parseDouble(newNode.getChildNodes().item(0).getNodeValue());
				}
			}
		}
		sd.annealingSchedules.addElement(annSched);
	}
	
	
	public static ServerInfo readServerInfo (org.w3c.dom.Node node)
	{
		if (debug) System.out.println("readServerInfo");
		org.w3c.dom.Node newNode = null;
		String hostname = null;
		long responseTime = ServerInfo.UNDEFINED;
		long speed = ServerInfo.UNDEFINED;
		for (int f = 0; f < node.getChildNodes().getLength(); f++)
		{
			newNode = node.getChildNodes().item(f);
			if (typeName[newNode.getNodeType()].equals("Element"))
			{
				if (newNode.getNodeName().toLowerCase().equals("hostname".toLowerCase()))
				{
					hostname = newNode.getChildNodes().item(0).getNodeValue();
				}
				if (newNode.getNodeName().toLowerCase().equals("speed".toLowerCase()))
				{
					speed = Long.parseLong(newNode.getChildNodes().item(0).getNodeValue());
				}
				if (newNode.getNodeName().toLowerCase().equals("responseTime".toLowerCase()))
				{
					responseTime = Long.parseLong(newNode.getChildNodes().item(0).getNodeValue());
				}
			}
		}
		ServerInfo serverInfo = new ServerInfo(hostname, speed);
		serverInfo.setResponseTime(responseTime);
		return serverInfo;
	}


	public SenecaDataset getSenecaDataset()
	{
		if (sd != null && parsingDone)
		{
			sd.init(); 
			return sd; 
		}
		return null;
	}





	private void initSD(AttributeList attrs)
	{

		sd = new SenecaDataset();
		if (attrs != null)
		{
			for (int i = 0; i < attrs.getLength (); i++)
			{
				if (attrs.getName(i).toLowerCase().equals("title"))
				{
					sd.setName(attrs.getValue (i));
				}
			}
		}
	}

